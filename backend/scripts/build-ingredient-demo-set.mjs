#!/usr/bin/env node
// Build Demo Mode's photo set -- and prove every photo works before shipping it.
//
// Demo Mode runs real inference at click time; nothing is stubbed. What is
// curated is the *input*: each photo is scanned here first, and only images the
// live model reads correctly are copied into frontend/public/demo/. So a
// walkthrough in front of judges shows the genuine pipeline, on inputs that were
// verified to work, instead of depending on finding a good photo in the moment.
//
// These images come from the dataset's official test split, which training never
// touched -- that is why they are a fair demonstration rather than a memorised
// answer. Licence: the Hub card declares none, so they are for local
// demonstration only and are not redistributed as a dataset.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const TRAINING = path.join(ROOT, 'training');
const OUT_DIR = path.join(ROOT, 'frontend', 'public', 'demo');
const MANIFEST_OUT = path.join(ROOT, 'frontend', 'src', 'data', 'demoPhotos.js');

const apiArg = process.argv.indexOf('--api');
const API = apiArg !== -1 ? process.argv[apiArg + 1] : 'http://localhost:5001';

// Pantry staples, chosen because a home cook would plausibly photograph exactly
// one of these, and because they read clearly in a small thumbnail.
const WANTED = [
  'tomatoes', 'onions', 'potatoes', 'garlic', 'ginger', 'carrots',
  'cauliflower', 'spinach_palak', 'chilli_pepper', 'lemon_lime',
  'cucumber', 'cabbage', 'bell_peppers_capsicum', 'green_peas',
];

const MIN_CONFIDENCE = 70;

const classMap = JSON.parse(fs.readFileSync(path.join(TRAINING, 'data', 'processed-ingredients', 'class_map.json'), 'utf8'));
const bySlug = new Map(classMap.classes.map((c) => [c.slug, c]));

const manifest = fs
  .readFileSync(path.join(TRAINING, 'data', 'processed-ingredients', 'manifest.jsonl'), 'utf8')
  .trim()
  .split('\n')
  .map((line) => JSON.parse(line))
  .filter((r) => r.split === 'test');

const pool = new Map();
for (const record of manifest) {
  const slug = record.labels[0];
  if (!pool.has(slug)) pool.set(slug, []);
  pool.get(slug).push(record);
}

async function scan(file) {
  const body = new FormData();
  body.append('image', new Blob([fs.readFileSync(file)], { type: 'image/jpeg' }), 'x.jpg');
  const res = await fetch(`${API}/api/vision-scan`, { method: 'POST', body });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

const chosen = [];
for (const slug of WANTED) {
  const cls = bySlug.get(slug);
  if (!cls) {
    console.log(`  skip ${slug.padEnd(24)} not a class in this model`);
    continue;
  }
  const expected = cls.canonical || cls.name;
  let picked = null;

  for (const record of (pool.get(slug) || []).slice(0, 6)) {
    const file = path.join(TRAINING, 'data', record.image);
    if (!fs.existsSync(file)) continue;
    let result;
    try {
      result = await scan(file);
    } catch (err) {
      console.error(`  ! ${slug}: ${err.message}`);
      break;
    }
    // The live scan must return exactly this ingredient, from the model itself
    // (not a CLIP fallback), with confidence to spare.
    if (result.source !== 'ingredient-model') continue;
    if (!result.data || result.data.length !== 1) continue;
    const got = result.data[0];
    if (got.name !== expected) continue;
    if (got.confidence < MIN_CONFIDENCE) continue;
    picked = { record, file, got };
    break;
  }

  if (picked) {
    chosen.push({ slug, label: expected, ...picked });
    console.log(`  ok   ${expected.padEnd(24)} ${picked.got.confidence}%  ${path.basename(picked.file)}`);
  } else {
    console.log(`  skip ${expected.padEnd(24)} no test image passed the ${MIN_CONFIDENCE}% bar`);
  }
}

if (chosen.length === 0) {
  console.error(`\nNothing verified -- is the backend running on ${API} with the ingredient model loaded?`);
  process.exit(1);
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const entries = chosen.map((c, index) => {
  const filename = `${String(index + 1).padStart(2, '0')}-${c.slug.replace(/_/g, '-')}.jpg`;
  fs.copyFileSync(c.file, path.join(OUT_DIR, filename));
  return {
    id: c.slug,
    label: c.label,
    category: bySlug.get(c.slug).category || 'Produce',
    file: `/demo/${filename}`,
    verifiedConfidence: c.got.confidence,
  };
});

fs.writeFileSync(
  MANIFEST_OUT,
  `// Generated by backend/scripts/build-ingredient-demo-set.mjs -- do not edit by hand.
//
// Every photo was scanned against the live model before being shipped and only
// images it reads correctly at >= ${MIN_CONFIDENCE}% are listed. Demo Mode still runs real
// inference on click; this file exists so the picker can label the photo and so a
// regression shows up as a failing verification instead of an embarrassing demo.
//
// Images: official test split of Nattakarn/fruit-and-vegetable-image-recognition
// (never seen during training). Licence undeclared -- local demonstration only.
export const DEMO_PHOTOS = ${JSON.stringify(entries, null, 2)};

export default DEMO_PHOTOS;
`
);

console.log(`\nwrote ${entries.length} verified photos -> frontend/public/demo/`);
console.log(`wrote ${path.relative(ROOT, MANIFEST_OUT)}`);
